_PH = re.compile(r"\{(\w+)(?:\.(\w+))?\}")


def fill(text: str, values: dict[str, str]) -> str:
    """{поле} або {поле.відмінок}: відмінок береться з довідника, інакше – введене значення."""
    def sub(m):
        key, case = m.group(1), m.group(2)
        if case == "role":
            return values.get(f"{key}.role") or "учня"
        return (values.get(f"{key}.{case}") if case else None) or values.get(key) or "…"
    return _PH.sub(sub, text)


P_JUST = "<p align='justify' style='margin:0; text-indent:0'>"


def render(t: Template, values: dict[str, str]) -> tuple[str, str]:
    """Повертає (заголовок, HTML тексту). «НАКАЗУЮ:» з нового рядка, без відступу (р. III п. 1)."""
    title = fill(t.title, values)
    esc = lambda s: html.escape(fill(s, values))  # noqa: E731
    parts = [f"{P_JUST}{esc(t.preamble)}</p>", "<p style='margin:12px 0 0 0'>НАКАЗУЮ:</p>"]
    for i, item in enumerate(t.items, 1):
        parts.append(f"{P_JUST}{i}. {esc(item)}</p>")
    return title, "".join(parts)


def types_by_kind() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for t in TEMPLATES:
        lst = out.setdefault(t.kind, [])
        if t.type not in lst:
            lst.append(t.type)
    return out
